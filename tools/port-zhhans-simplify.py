def main():
    apply = "--apply" in sys.argv

    text = open(PATH, "rb").read().decode("utf-8-sig").lstrip("\ufeff")
    lines = text.replace("\r\n", "\n").split("\n")

    heads = [i for i, line in enumerate(lines) if line.startswith("## ")]

    touched = 0

    for chapter in CHAPTERS:
        start = heads[chapter]
        end = heads[chapter + 1] if len(heads) > chapter + 1 else len(lines)

        for i in range(start, end):
            before = lines[i]
            after = "".join(PAIRS.get(ch, ch) for ch in before)

            if after != before:
                touched += 1

                if not apply:
                    print(f"第 {chapter + 1} 章 · {before[:56]}")

                lines[i] = after

    print(f"\n{touched} 行会变（共 {len(CHAPTERS)} 章）")

    if not apply:
        return

    out = "\n".join(lines)

    if not out.endswith("\n"):
        out += "\n"

    # 保 BOM。
    with io.open(PATH, "wb") as handle:
        handle.write(b"\xef\xbb\xbf" + out.encode("utf-8"))

    print("已写")


if __name__ == "__main__":
    main()
